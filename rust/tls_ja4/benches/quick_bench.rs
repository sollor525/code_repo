use criterion::{black_box, criterion_group, criterion_main, Criterion};
use tls_ja4::is_tls_packet;

// 简单的TLS数据包
fn create_tls_packet() -> Vec<u8> {
    vec![
        0x16, 0x03, 0x01, 0x00, 0x4a, // TLS Record Header
        0x01, 0x00, 0x00, 0x46, // Handshake Header
        0x03, 0x03, // TLS Version
        0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, // Random
        0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f,
        0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17,
        0x18, 0x19, 0x1a, 0x1b, 0x1c, 0x1d, 0x1e, 0x1f,
        0x00, // Session ID length
        0x00, 0x08, // Cipher suites length
        0x00, 0x2f, 0x00, 0x35, 0x00, 0x3c, 0x00, 0x3d, // Cipher suites
        0x01, // Compression methods length
        0x00, // Compression method
        0x00, 0x1a, // Extensions length
        0x00, 0x0a, 0x00, 0x08, 0x00, 0x06, 0x00, 0x17, 0x00, 0x18, 0x00, 0x19,
        0x00, 0x0b, 0x00, 0x02, 0x01, 0x00,
        0x00, 0x0d, 0x00, 0x0a, 0x00, 0x08, 0x04, 0x01, 0x05, 0x01, 0x02, 0x01, 0x04, 0x03,
    ]
}

fn bench_tls_detection(c: &mut Criterion) {
    let tls_packet = create_tls_packet();
    
    c.bench_function("is_tls_packet", |b| {
        b.iter(|| {
            let result = is_tls_packet(black_box(&tls_packet));
            black_box(result)
        })
    });
}

criterion_group!(benches, bench_tls_detection);
criterion_main!(benches);
