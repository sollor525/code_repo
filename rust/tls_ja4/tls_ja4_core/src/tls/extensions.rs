//! TLS扩展解析功能
#[rustfmt::skip]
/// 检测是否为GREASE扩展
pub fn is_grease_extension(ext_type: u16) -> bool {
    // GREASE扩展类型是0x0a0a, 0x1a1a, 0x2a2a, 0x3a3a, 0x4a4a, 0x5a5a, 0x6a6a, 0x7a7a,
    // 0x8a8a, 0x9a9a, 0xaaaa, 0xbaba, 0xcaca, 0xdada, 0xeaea, 0xfafa
    let high_byte = (ext_type >> 8) as u8;
    let low_byte = (ext_type & 0xff) as u8;


    high_byte == low_byte &&
    matches!(high_byte, 0x0a | 0x1a | 0x2a | 0x3a | 0x4a | 0x5a | 0x6a | 0x7a | 0x8a | 0x9a | 0xaa | 0xba | 0xca | 0xda | 0xea | 0xfa)
}

#[rustfmt::skip]
/// 检测是否为GREASE密码套件
pub fn is_grease_cipher(cipher: u16) -> bool {
    // GREASE密码套件是0x0a0a, 0x1a1a, 0x2a2a, 0x3a3a, 0x4a4a, 0x5a5a, 0x6a6a, 0x7a7a,
    // 0x8a8a, 0x9a9a, 0xaaaa, 0xbaba, 0xcaca, 0xdada, 0xeaea, 0xfafa
    let high_byte = (cipher >> 8) as u8;
    let low_byte = (cipher & 0xff) as u8;

    //要求 高 4 位等于低 4 位
    //并且要求这个相同的 4 位值落在 0xA 到 0xF 的 16 个候选里
    high_byte == low_byte &&
    matches!(high_byte, 0x0a | 0x1a | 0x2a | 0x3a | 0x4a | 0x5a | 0x6a | 0x7a | 0x8a | 0x9a | 0xaa | 0xba | 0xca | 0xda | 0xea | 0xfa)
}
